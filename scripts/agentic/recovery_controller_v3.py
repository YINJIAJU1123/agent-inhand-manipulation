"""Independent optimization and a baseline-preserving recovery parametrization.

The critic and outcome predictor own separate encoders. Their optimizer steps
cannot move the action policy outside PPO's trust-region check. The outcome
predictor is still an empirical rollout-outcome model, not an oracle safety value.
"""
import copy
import random
import torch
from torch import nn
from torch.distributions import Independent,Normal,kl_divergence
from recovery_controller_v2 import observation,bridge_fraction,fixed_command,advantages


def residual_command(proposal,current,raw_action,fraction,pending,residual_bound=.02):
    # Mean-zero policy exactly equals fixed slow during wait and immediate
    # student execution after the response. Recovery slowing must be learned.
    wait_speed=torch.sigmoid(torch.logit(torch.full_like(fraction,.15))+4*raw_action[:,0].tanh())
    resume_speed=1-.85*(-raw_action[:,0].tanh()).clamp_min(0)*(1-fraction)
    speed=torch.where(pending,wait_speed,resume_speed)
    residual=residual_bound*raw_action[:,1:].tanh()*(1-fraction[:,None])
    # Avoid a subtract/add round trip when forwarding the original student.
    # Even tiny GPU rounding changes can affect a contact trajectory.
    base=torch.where(speed[:,None]==1.,proposal,current+speed[:,None]*(proposal-current))
    return (base+residual).clamp(-1,1),speed,residual


class Encoder(nn.Module):
    def __init__(self,obs_dim,goal_dim):
        super().__init__()
        self.sensor=nn.Sequential(nn.Linear(obs_dim,192),nn.LayerNorm(192),nn.Tanh())
        self.goal=nn.Sequential(nn.Linear(goal_dim,64,bias=False),nn.LayerNorm(64),nn.Tanh())
        self.fusion=nn.Sequential(nn.Linear(256,128),nn.Tanh())
    def forward(self,obs,goal):
        return self.fusion(torch.cat((self.sensor(obs),self.goal(nn.functional.normalize(goal,dim=-1))),-1))


class RecoveryController(nn.Module):
    def __init__(self,obs_dim,goal_dim=768,action_dim=21,privileged_dim=8):
        super().__init__()
        self.obs_dim,self.goal_dim,self.action_dim=obs_dim,goal_dim,action_dim
        self.policy_encoder=Encoder(obs_dim,goal_dim)
        self.actor=nn.Linear(128,action_dim+1)
        self.log_std=nn.Parameter(torch.full((action_dim+1,),-3.))
        self.value_encoder=Encoder(obs_dim,goal_dim)
        self.critic=nn.Sequential(nn.Linear(128+privileged_dim,128),nn.Tanh(),nn.Linear(128,1))
        self.outcome_encoder=Encoder(obs_dim,goal_dim)
        self.outcome=nn.Linear(128,1)
        nn.init.zeros_(self.actor.weight);nn.init.zeros_(self.actor.bias)
    def distribution(self,obs,goal):
        return Independent(Normal(self.actor(self.policy_encoder(obs,goal)),self.log_std.clamp(-4,-1.5).exp()),1)
    def value(self,obs,goal,privileged):
        return 12.*self.critic(torch.cat((self.value_encoder(obs,goal),privileged),-1)).squeeze(-1)
    def outcome_logit(self,obs,goal):
        return self.outcome(self.outcome_encoder(obs,goal)).squeeze(-1)
    def parameters_for(self,part):
        if part=='policy':return list(self.policy_encoder.parameters())+list(self.actor.parameters())+[self.log_std]
        if part=='value':return list(self.value_encoder.parameters())+list(self.critic.parameters())
        if part=='outcome':return list(self.outcome_encoder.parameters())+list(self.outcome.parameters())
        raise ValueError(part)


def make_optimizers(model):
    groups={part:model.parameters_for(part) for part in ('policy','value','outcome')}
    ids=[{id(p) for p in v} for v in groups.values()]
    assert all(not ids[i]&ids[j] for i in range(3) for j in range(i))
    return {part:torch.optim.Adam(params,lr=5e-5 if part=='policy' else 2e-4) for part,params in groups.items()}


class OutcomeReplay:
    """Uniform episode sampling; validation cases are kept out of fitting.

    Labels were generated by changing behavior policies, which limits their
    interpretation. Splitting by whole reset seed prevents frame-level leakage.
    """
    def __init__(self,max_episodes=256):
        self.train=[];self.validation=[];self.max_episodes=max_episodes
        self.rng=random.Random(181027)
    def add(self,rollout,success,seed):
        valid=torch.stack([r['valid'] for r in rollout])
        for slot in range(len(success)):
            times=valid[:,slot].nonzero().flatten()[::8].tolist()
            if not times:continue
            case=dict(obs=torch.stack([rollout[t]['obs'][slot] for t in times]).cpu(),
                      goal=rollout[0]['goal'][slot].cpu(),target=float(success[slot]),seed=seed,slot=slot)
            bucket=self.validation if seed%5==0 else self.train
            bucket.append(case)
            del bucket[:max(0,len(bucket)-self.max_episodes)]
    def fit(self,model,optimizer,device,steps=12,batch_size=128):
        if not self.train:return dict(outcome_train_episodes=0)
        losses=[]
        for _ in range(steps):
            cases=self.rng.choices(self.train,k=batch_size)
            x=torch.stack([c['obs'][self.rng.randrange(len(c['obs']))] for c in cases]).to(device)
            g=torch.stack([c['goal'] for c in cases]).to(device)
            y=torch.tensor([c['target'] for c in cases],device=device)
            loss=nn.functional.binary_cross_entropy_with_logits(model.outcome_logit(x,g),y)
            optimizer.zero_grad();loss.backward()
            nn.utils.clip_grad_norm_(model.parameters_for('outcome'),1.,error_if_nonfinite=True);optimizer.step()
            losses.append(float(loss.detach()))
        prior=sum(c['target'] for c in self.train)/len(self.train)
        scores=[];prior_scores=[]
        with torch.no_grad():
            for c in self.validation:
                x=c['obs'].to(device);g=c['goal'].to(device).expand(len(x),-1)
                prob=model.outcome_logit(x,g).sigmoid()
                scores.append(float(((prob-c['target'])**2).mean()))
                prior_scores.append((prior-c['target'])**2)
        return dict(outcome_train_episodes=len(self.train),outcome_validation_episodes=len(self.validation),
                    outcome_bce=sum(losses)/len(losses),outcome_validation_brier=sum(scores)/len(scores) if scores else None,
                    outcome_prior_validation_brier=sum(prior_scores)/len(prior_scores) if scores else None)


def update(model,optimizers,rollout,success,*,objective='completion',epochs=3,replay=None,seed=None,target_kl=.02):
    keys=('obs','goal','priv','action','logprob','value','reward','done','valid','mean','std')
    x,g,z,act,oldlog,values,rewards,done,valid,oldmean,oldstd=[torch.stack([r[k] for r in rollout]) for k in keys]
    adv=advantages(rewards,values,done,valid);returns=(adv+values)[valid]
    x,g,z,act,oldlog,oldmean,oldstd,adv=[v[valid] for v in (x,g,z,act,oldlog,oldmean,oldstd,adv)]
    if len(x)<2:raise RuntimeError('Too few controller decisions')
    adv=(adv-adv.mean())/adv.std().clamp_min(1e-6)
    # Value fitting has no gradient path to the policy.
    value_losses=[]
    for _ in range(epochs):
        for ids in torch.randperm(len(x),device=x.device).split(256):
            loss=((model.value(x[ids],g[ids],z[ids])-returns[ids])/12.).square().mean()
            optimizers['value'].zero_grad();loss.backward()
            nn.utils.clip_grad_norm_(model.parameters_for('value'),1.,error_if_nonfinite=True);optimizers['value'].step()
            value_losses.append(float(loss.detach()))
    policy_losses=[];kls=[];rolled_back=False
    olddist=Independent(Normal(oldmean,oldstd),1)
    policy_params=model.parameters_for('policy')
    for _ in range(epochs):
        if rolled_back:break
        for ids in torch.randperm(len(x),device=x.device).split(256):
            dist=model.distribution(x[ids],g[ids]);log=dist.log_prob(act[ids]);ratio=(log-oldlog[ids]).exp()
            loss=-torch.minimum(ratio*adv[ids],ratio.clamp(.8,1.2)*adv[ids]).mean()-.001*dist.entropy().mean()
            if not torch.isfinite(loss):raise RuntimeError('Nonfinite policy loss')
            previous=[p.detach().clone() for p in policy_params]
            state=copy.deepcopy(optimizers['policy'].state_dict())
            optimizers['policy'].zero_grad();loss.backward()
            nn.utils.clip_grad_norm_(policy_params,1.,error_if_nonfinite=True);optimizers['policy'].step()
            with torch.no_grad():kl=float(kl_divergence(olddist,model.distribution(x,g)).mean())
            if not torch.isfinite(torch.tensor(kl)) or kl>target_kl:
                with torch.no_grad():
                    for p,before in zip(policy_params,previous):p.copy_(before)
                optimizers['policy'].load_state_dict(state);rolled_back=True;break
            policy_losses.append(float(loss.detach()));kls.append(kl)
    with torch.no_grad():final_kl=float(kl_divergence(olddist,model.distribution(x,g)).mean())
    if final_kl>target_kl+1e-6:raise RuntimeError('KL guard failed')
    stats=dict(samples=len(x),policy_loss=sum(policy_losses)/max(1,len(policy_losses)),value_normalized_loss=sum(value_losses)/len(value_losses),
               final_exact_kl=final_kl,max_accepted_kl=max(kls,default=0.),accepted_policy_steps=len(kls),kl_rollback=rolled_back)
    if replay is not None and objective=='completion':
        replay.add(rollout,success,seed);stats.update(replay.fit(model,optimizers['outcome'],x.device))
    # Auxiliary replay fitting is also isolated from policy parameters.
    with torch.no_grad():after=float(kl_divergence(olddist,model.distribution(x,g)).mean())
    if abs(after-final_kl)>1e-7:raise RuntimeError('Auxiliary update moved the actor')
    return stats
